_lang = "en"


def system_language():
    """Italian if the Windows UI language is Italian, otherwise English."""
    try:
        primary = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF
    except Exception:
        return "en"
    return "it" if primary == 0x10 else "en"


def set_language(pref, acestep_lang=None):
    """pref: "auto" (Windows language), "it", "en", or "acestep" (same language as ACE-Step's interface)."""
    global _lang
    if pref == "acestep":
        _lang = acestep_lang if acestep_lang in STRINGS else "en"
    else:
        _lang = pref if pref in ("it", "en") else system_language()
    return _lang


def current():
    return _lang


